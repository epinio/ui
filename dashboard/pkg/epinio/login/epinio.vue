<script setup lang="ts">
import { onMounted, ref } from 'vue';
import { useStore } from 'vuex';
import epinioAuth from '../utils/auth';
import { isSameOriginEpinioApi } from '../utils/standalone-api';

const store = useStore();
const loading = ref<boolean>(true);
let redirectOpts = ref<object>({});
const t = store.getters['i18n/t'];

const props = defineProps<{
  name: string;
}>();

onMounted(async () => {
  // Production (same-origin Epinio API): resume if server session cookies exist.
  if (await isSameOriginEpinioApi()) {
    try {
      const me = await fetch('/api/v1/me', { credentials: 'include' });

      if (me.ok) {
        await epinioAuth.syncShellSession();
        await store.dispatch('auth/getUserPrincipal');
        loading.value = false;

        return;
      }
    } catch {
      // fall through to OIDC start button
    }

    loading.value = false;

    return;
  }

  /* Local Jetstream: keep the classic Dex redirectUrl flow so Shell login works.
  *
  * The dashboard would normally get this directly from the auth provider,
  * however epinio/dex implement pkce flow (additional per request validation).
  * To support this the redirect url is per request and thus generated by the
  * BE per login. */
  const baseNonce = await store.dispatch(
    'auth/createNonce',
    { provider: 'epinio' },
  );
  const encodedNonce = await store.dispatch('auth/encodeNonce', baseNonce);
  const res = await store.dispatch(
    'management/request',
    { url: `/dex/redirectUrl?state=${ encodedNonce }` },
  );

  const redirectAsUrl = new URL(res.redirectUrl);
  const pkceCodeVerifier = redirectAsUrl.searchParams.get('code_verifier');
  const scopes = redirectAsUrl.searchParams.get(`scope`);

  redirectAsUrl.searchParams.delete('scope');

  redirectOpts.value = {
    provider: props.name,
    redirectUrl: redirectAsUrl.toString(),
    scopes: scopes.split(' '),
    scopesJoinChar: ' ',
    nonce: baseNonce,
    persistNonce: {
      ...baseNonce,
      pkceCodeVerifier
    }
  };

  loading.value = false;
});

async function login() {
  if (await isSameOriginEpinioApi()) {
    window.location.assign('/api/v1/auth/oidc/start');

    return;
  }

  store.dispatch('auth/redirectTo', redirectOpts.value);
}
</script>

<template>
  <div class="text-center">
    <button
      ref="btn"
      class="btn bg-primary"
      style="font-size: 18px;"
      :disabled="loading"
      @click="login"
    >
      {{ t('epinio.login.genericProvider') }}
    </button>
  </div>
</template>
